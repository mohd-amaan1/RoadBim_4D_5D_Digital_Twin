-- Drop Existing Tables for Clean Re-run
DROP TABLE IF EXISTS "LayerProgress"  CASCADE;
DROP TABLE IF EXISTS "SiteHotspots"   CASCADE;
DROP TABLE IF EXISTS "RoadLayers"     CASCADE;
DROP TABLE IF EXISTS "RoadChainages"  CASCADE;
DROP TABLE IF EXISTS "ProjectMetrics" CASCADE;

-- 1. Table: RoadChainages (100 KM Alignment Broken into 1 KM Sections)
CREATE TABLE "RoadChainages" (
    "Id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ChainageStart"  double precision NOT NULL,          -- e.g. 12.0 (KM 12.000)
    "ChainageEnd"    double precision NOT NULL,          -- e.g. 13.0 (KM 13.000)
    "KmLabel"        text NOT NULL,                      -- e.g. 'KM 012 - KM 013'
    "SectionName"    text NOT NULL,                      -- e.g. 'Highway Corridor Segment 13'
    "Latitude"       double precision NOT NULL,          -- GIS Coordinate Start
    "Longitude"      double precision NOT NULL,          -- GIS Coordinate Start
    "Elevation"      double precision NOT NULL DEFAULT 120.5, -- Terrain elevation in meters
    "TerrainType"    text NOT NULL DEFAULT 'Cut & Fill'
);

-- 2. Table: RoadLayers (Pavement & Sub-surface Layer Catalog)
CREATE TABLE "RoadLayers" (
    "Id"              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "LayerName"       text NOT NULL,           -- e.g. 'Subgrade Earthwork'
    "Code"            text NOT NULL UNIQUE,    -- 'SUB', 'GSB', 'WMM', 'DBM', 'BC'
    "ThicknessMm"     integer NOT NULL,        -- Thickness in millimeters
    "MaterialType"    text NOT NULL,
    "DefaultColorHex" text NOT NULL,           -- e.g. '#64748B'
    "SortOrder"       integer NOT NULL         -- 1=Subgrade (bottom), 5=BC Surface (top)
);

-- 3. Table: LayerProgress (Live Excel Import Data & 4D Progress Records)
CREATE TABLE "LayerProgress" (
    "Id"                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ChainageId"        integer NOT NULL REFERENCES "RoadChainages"("Id") ON DELETE CASCADE,
    "LayerId"           integer NOT NULL REFERENCES "RoadLayers"("Id")    ON DELETE CASCADE,
    "Status"            text NOT NULL CHECK ("Status" IN ('Completed', 'In-Progress', 'Delayed', 'Not Started')),
    "ProgressPercent"   double precision NOT NULL CHECK ("ProgressPercent" >= 0 AND "ProgressPercent" <= 100),
    "DesignThicknessMm" integer NULL,                    -- Chainage-specific thickness override in mm
    "TopLevelMeters"    double precision NULL,           -- Calculated Top Elevation (RL) in meters
    "BaseLevelMeters"   double precision NULL,           -- Calculated Base Elevation (RL) in meters
    "LevelColorHex"     text NULL,                       -- Level-wise custom display color hex
    "PlannedStartDate"  timestamptz NOT NULL,
    "PlannedEndDate"    timestamptz NOT NULL,
    "ActualStartDate"   timestamptz NULL,
    "ActualEndDate"     timestamptz NULL,
    "BudgetCost"        numeric(18,2) NOT NULL DEFAULT 0.00,
    "ActualCost"        numeric(18,2) NOT NULL DEFAULT 0.00,
    "CostVariance"      numeric(18,2) NOT NULL DEFAULT 0.00,
    "DelayDays"         integer NOT NULL DEFAULT 0,
    "UpdatedBy"         text NOT NULL DEFAULT 'System Excel Import',
    "UpdatedAt"         timestamptz NOT NULL DEFAULT now()
);

-- 4. Table: SiteHotspots (Geo-Tagged 360 Site Photos, Drone Logs & Issues)
CREATE TABLE "SiteHotspots" (
    "Id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ChainageId"     integer NOT NULL REFERENCES "RoadChainages"("Id"),
    "Title"          text NOT NULL,
    "Description"    text NOT NULL,
    "Category"       text NOT NULL CHECK ("Category" IN ('Photo360', 'DroneInspection', 'QualityIssue', 'SafetyAudit')),
    "ImageUrl"       text NOT NULL,
    "InspectionDate" timestamptz NOT NULL DEFAULT now(),
    "InspectorName"  text NOT NULL,
    "Status"         text NOT NULL DEFAULT 'Open'
);

-- 5. Table: ProjectMetrics (Executive Summary Dashboard Cache)
CREATE TABLE "ProjectMetrics" (
    "Id"                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TotalKmTarget"            double precision NOT NULL DEFAULT 100.0,
    "TotalKmCompleted"         double precision NOT NULL,
    "OverallProgressPercent"   double precision NOT NULL,
    "SchedulePerformanceIndex" double precision NOT NULL, -- SPI = EV / PV
    "CostPerformanceIndex"     double precision NOT NULL, -- CPI = EV / AC
    "TotalBudgetCost"          numeric(18,2) NOT NULL,
    "TotalActualCost"          numeric(18,2) NOT NULL,
    "DelayedSectionsCount"     integer NOT NULL,
    "CalculatedAt"             timestamptz NOT NULL DEFAULT now()
);

-- Indexes for High Performance Queries across the 100 KM Dataset
